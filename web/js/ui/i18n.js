let lang = "en";

export function getLang() {
  return lang;
}

/** Translate a key, filling {placeholders} from vars. Falls back to English. */
export function t(key, vars = {}, forLang = lang) {
  const s = STRINGS[forLang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** Switch language: updates <html lang> and every [data-i18n] element under root. */
export function setLang(next, root = globalThis.document) {
  lang = STRINGS[next] ? next : "en";
  if (!root) return lang;
  root.documentElement.lang = lang;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
  return lang;
}
